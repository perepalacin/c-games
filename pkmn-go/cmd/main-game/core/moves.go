	LowerSpeed
	RaiseSpecialAttack
	LowerSpecialAttack
	LowerSpecialDefense
	RaiseSpecialDefense
	Protection
	Faint
	Poisoning
	Confusion
	Flinching
	Trapped
	LowHealthRegen
	HitsMultipleTimes
	Burning
	Frezing
	Paralyzing
	Draining
	RaiseAccuracy
	LowerAccuracy
	Sleeping
