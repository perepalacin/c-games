type MoveSideEffect struct {
	sideEffect SideEffect
	target     Target
	atTheStart bool
}

type PkmnMove struct {
	name          string
	totalPP       uint8
	currentPP     uint8
	moveType      PkmnType
	category      CategoryKey
	power         uint8
	accuracy      uint8
	probability   uint8
	requiredLevel uint8
	sideEffects   []MoveSideEffect
}

func createNewMoveWrapper(name string, totalPP uint8, moveType PkmnType, category CategoryKey, power uint8, accuracy uint8, probability uint8) PkmnMove {
	return PkmnMove{
		name:          name,
		totalPP:       totalPP,
		currentPP:     totalPP,
		moveType:      moveType,
		category:      category,
		power:         power,
		accuracy:      accuracy,
		probability:   probability,
		requiredLevel: 0,
		sideEffects:   []MoveSideEffect{},
	}
}

